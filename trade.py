def trade_exam_question(index, score=0):
    question = TRADE_QUESTIONS[index]
    keyboard = []
    for i, option in enumerate(question["options"]):
        keyboard.append(
            [
                InlineKeyboardButton(
                    f"{chr(65 + i)}) {option}",
                    callback_data=f"trade_answer_{index}_{i}_{score}"
                )
            ]
        )
    keyboard.append(
        [
            InlineKeyboardButton(
                "❌ خروج از آزمون",
                callback_data="trade"
            )
        ]
    )
    text = f"""
📝 آزمون تجارت بین‌الملل
سؤال {index + 1} از {len(TRADE_QUESTIONS)}
{question["question"]}
👇 پاسخ صحیح را انتخاب کنید:
"""
