    keyboard = []
    for i, option in enumerate(question["options"]):
        keyboard.append(
            [
                InlineKeyboardButton(
                    f"{chr(65 + i)}) {option}",
                    callback_data=(
                        f"marketing_answer_{index}_{i}_{score}"
                    )
                )
            ]
        )
    keyboard.append(
        [
            InlineKeyboardButton(
                "❌ خروج از آزمون",
                callback_data="marketing"
            )
        ]
    )
